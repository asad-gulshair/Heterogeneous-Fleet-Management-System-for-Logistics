"""Layout designs on disk, with versions.

    data/designs/<id>/v001.json, v002.json ...   every save is a new version (nothing is overwritten)
    data/compiled/<id>-v001.yaml                 simulation config the twin runs
    data/backgrounds/<sha>.png|jpg               uploaded floor plans (same file uploaded twice = stored once)
    data/robots.json                             custom robot types saved for reuse in other layouts
    config/layouts/*.json                        read-only example layouts (templates)

Step 2 moves this into the database; the interface (list / get / save / versions) stays the same.
"""
from __future__ import annotations
import hashlib
import io
import json
import os
import re
import time
import uuid
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(os.environ.get("TUSCORE_DATA", str(ROOT / "data")))
TEMPLATES = ROOT / "config" / "layouts"
DESIGNS = DATA / "designs"
COMPILED = DATA / "compiled"
BACKGROUNDS = DATA / "backgrounds"
ROBOTS = DATA / "robots.json"
MAX_UPLOAD = 40 * 1024 * 1024
MAX_PX = 8000                 # longest side kept for an image plan
PDF_DPI, PDF_MAX_PX = 150, 7000
_ID = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")


def _check_id(did: str) -> str:
    if not _ID.match(did or ""):
        raise KeyError(did)
    return did


def _versions(d: Path) -> list[int]:
    return sorted(int(p.stem[1:]) for p in d.glob("v*.json") if p.stem[1:].isdigit())


def list_designs() -> list[dict]:
    out = []
    for p in sorted(TEMPLATES.glob("*.json")):
        L = json.loads(p.read_text(encoding="utf-8"))
        out.append({"id": p.stem, "name": L.get("name"), "template": True, "description": L.get("description", ""),
                    "versions": 1, "updated": None, "size": [L.get("width_m"), L.get("height_m")]})
    if DESIGNS.exists():
        rows = []
        for d in DESIGNS.iterdir():
            vs = _versions(d) if d.is_dir() else []
            if not vs:
                continue
            f = d / f"v{vs[-1]:03d}.json"
            L = json.loads(f.read_text(encoding="utf-8"))
            rows.append({"id": d.name, "name": L.get("name"), "template": False, "description": L.get("description", ""),
                         "versions": len(vs), "updated": f.stat().st_mtime, "size": [L.get("width_m"), L.get("height_m")]})
        out += sorted(rows, key=lambda r: -r["updated"])
    return out


def get(did: str, version: int | None = None) -> dict:
    _check_id(did)
    t = TEMPLATES / f"{did}.json"
    if t.exists():
        L = json.loads(t.read_text(encoding="utf-8"))
        return {"id": did, "template": True, "version": 1, "versions": [1], "layout": L}
    d = DESIGNS / did
    vs = _versions(d) if d.exists() else []
    if not vs:
        raise KeyError(did)
    v = vs[-1] if version is None else version
    if v not in vs:
        raise KeyError(f"{did} v{version}")
    L = json.loads((d / f"v{v:03d}.json").read_text(encoding="utf-8"))
    return {"id": did, "template": False, "version": v, "versions": vs, "layout": L}


def versions(did: str) -> list[dict]:
    _check_id(did)
    d = DESIGNS / did
    out = []
    for v in _versions(d) if d.exists() else []:
        f = d / f"v{v:03d}.json"
        L = json.loads(f.read_text(encoding="utf-8"))
        out.append({"version": v, "saved": f.stat().st_mtime, "note": L.get("note", ""), "elements": len(L.get("elements", []))})
    return out


def _slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", (name or "layout").lower()).strip("-")[:40] or "layout"
    return f"{s}-{uuid.uuid4().hex[:6]}"


def save(layout: dict, did: str | None = None, note: str = "") -> dict:
    """Create a design (did=None or a template id) or add a version to an existing one."""
    if did and (TEMPLATES / f"{did}.json").exists():
        did = None                                  # saving a template makes your own copy
    did = _check_id(did) if did else _slug(layout.get("name"))
    d = DESIGNS / did
    d.mkdir(parents=True, exist_ok=True)
    vs = _versions(d)
    v = (vs[-1] + 1) if vs else 1
    L = dict(layout, note=note[:200], saved_at=time.time())
    (d / f"v{v:03d}.json").write_text(json.dumps(L, indent=1), encoding="utf-8")
    return {"id": did, "version": v}


def write_compiled(did: str, version: int, cfg: dict) -> Path:
    COMPILED.mkdir(parents=True, exist_ok=True)
    p = COMPILED / f"{_check_id(did)}-v{version:03d}.yaml"
    p.write_text("# Generated by the TusCore Layout Designer - edit the layout, not this file.\n"
                 + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return p


# ---------------------------------------------------------------- custom robot library
def robot_library() -> dict:
    try:
        return json.loads(ROBOTS.read_text(encoding="utf-8")) if ROBOTS.exists() else {}
    except (OSError, ValueError):
        return {}


def save_robot(key: str, d: dict) -> dict:
    lib = robot_library()
    lib[key] = d
    ROBOTS.parent.mkdir(parents=True, exist_ok=True)
    ROBOTS.write_text(json.dumps(lib, indent=1), encoding="utf-8")
    return lib


def delete_robot(key: str) -> dict:
    lib = robot_library()
    if lib.pop(key, None) is not None:
        ROBOTS.write_text(json.dumps(lib, indent=1), encoding="utf-8")
    return lib


# ---------------------------------------------------------------- floor plan uploads
class UploadError(ValueError):
    pass


def _store_image(img, tag: bytes, name: str, extra: dict, photo: bool = False) -> dict:
    from PIL import Image
    if max(img.size) > MAX_PX:
        k = MAX_PX / max(img.size)
        img = img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.LANCZOS)
    line_art = not photo           # drawings stay sharp (PNG); photos of a plan go to JPEG
    if img.mode not in ("RGB", "L"):
        img = img.convert("RGBA" if "A" in img.mode or img.mode == "P" else "RGB")
        if img.mode == "RGBA":                       # plans on transparent background -> white paper
            bg = Image.new("RGB", img.size, "white")
            bg.paste(img, mask=img.split()[3])
            img = bg
    buf = io.BytesIO()
    ext = "png" if line_art else "jpg"
    img.save(buf, "PNG", optimize=True) if ext == "png" else img.save(buf, "JPEG", quality=88)
    bid = f"{hashlib.sha256(tag).hexdigest()[:24]}.{ext}"
    BACKGROUNDS.mkdir(parents=True, exist_ok=True)
    f = BACKGROUNDS / bid
    if not f.exists():
        f.write_bytes(buf.getvalue())
    return {"id": bid, "name": name[:120], "w_px": img.width, "h_px": img.height, **extra}


def _render_pdf(data: bytes, page: int, name: str, source: str) -> dict:
    try:
        import pypdfium2 as pdfium
    except ImportError:
        raise UploadError("PDF support is not installed (pip install pypdfium2). Export the plan as PNG or JPG instead.")
    try:
        pdf = pdfium.PdfDocument(data)
    except Exception:
        raise UploadError("This PDF cannot be opened. Is it password-protected or damaged?")
    n = len(pdf)
    if not 1 <= page <= n:
        raise UploadError(f"The PDF has {n} page{'s' if n > 1 else ''}.")
    pg = pdf[page - 1]
    w_pt, h_pt = pg.get_size()
    scale = min(PDF_DPI / 72, PDF_MAX_PX / max(w_pt, h_pt))
    img = pg.render(scale=scale).to_pil()
    # paper size in mm, so the user can see it is A1/A0 etc. (1 pt = 25.4/72 mm)
    extra = {"pages": n, "page": page, "source": source, "paper_mm": [round(w_pt * 25.4 / 72), round(h_pt * 25.4 / 72)]}
    return _store_image(img, f"{source}:{page}".encode(), name, extra)


def save_background(data: bytes, name: str = "", page: int = 1) -> dict:
    """Store an uploaded floor plan (PNG, JPG, WEBP, BMP, TIFF, GIF or PDF). Returns the image the designer shows."""
    if not data:
        raise UploadError("The file is empty.")
    if len(data) > MAX_UPLOAD:
        raise UploadError(f"The file is larger than {MAX_UPLOAD // 2**20} MB. Export a smaller image or PDF.")
    sha = hashlib.sha256(data).hexdigest()[:24]
    if data[:5] == b"%PDF-":
        src = BACKGROUNDS / "src" / f"{sha}.pdf"
        src.parent.mkdir(parents=True, exist_ok=True)
        if not src.exists():
            src.write_bytes(data)
        return _render_pdf(data, page, name, sha)
    from PIL import Image, ImageOps, UnidentifiedImageError
    Image.MAX_IMAGE_PIXELS = 400_000_000
    try:
        img = Image.open(io.BytesIO(data))
        fmt = img.format
        img = ImageOps.exif_transpose(img) or img
        img.format = fmt
        img.load()
    except (UnidentifiedImageError, OSError, Image.DecompressionBombError):
        low = name.lower()
        hint = " DWG/DXF drawings: export the plan from your CAD tool as PDF first." if low.endswith((".dwg", ".dxf")) else ""
        raise UploadError("Unsupported file. Use PNG, JPG or PDF." + hint)
    photo = (img.format or "").upper() in ("JPEG", "MPO", "WEBP") if hasattr(img, "format") else False
    return _store_image(img, data, name, {"pages": 1, "page": 1, "source": ""}, photo=photo)


def background_page(source: str, page: int, name: str = "") -> dict:
    if not re.fullmatch(r"[0-9a-f]{24}", source or ""):
        raise KeyError(source)
    src = BACKGROUNDS / "src" / f"{source}.pdf"
    if not src.exists():
        raise KeyError(source)
    return _render_pdf(src.read_bytes(), page, name, source)


def background_file(bid: str) -> Path:
    if not re.fullmatch(r"[0-9a-f]{16,64}\.(png|jpg)", bid or ""):
        raise KeyError(bid)
    f = BACKGROUNDS / bid
    if not f.exists():
        raise KeyError(bid)
    return f
